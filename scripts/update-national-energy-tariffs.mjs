fs.writeFileSync(OUTPUT, output, "utf8");
console.log(`Generated ${rules.length} automatic energy tariff rules in ${OUTPUT}`);

function selectStandardResidentialPair(rows) {
  if (!rows.length) return null;

  // A base da ANEEL contém várias linhas B1 simultaneamente (bases econômicas,
  // detalhes e agentes acessantes). Primeiro priorizamos a linha de aplicação
  // residencial convencional mais genérica; só depois resolvemos o par TUSD+TE.
  const scored = rows.map((row) => ({ row, score: residentialRowScore(row) }));
  const maxScore = Math.max(...scored.map((item) => item.score));
  const bestRows = scored.filter((item) => item.score === maxScore).map((item) => item.row);
  const pairCounts = countPairs(bestRows);

  if (pairCounts.length === 1) {
    return {
      pair: pairCounts[0].pair,
      representative: bestRows.find((row) => samePair(row, pairCounts[0].pair))
    };
  }

  // Se ainda houver duplicidade, aceitamos somente um par claramente dominante
  // entre linhas semanticamente equivalentes. Empates continuam bloqueados.
  pairCounts.sort((a, b) => b.count - a.count);
  if (pairCounts.length && pairCounts[0].count > (pairCounts[1]?.count || 0)) {
    const winner = pairCounts[0].pair;
    return {
      pair: winner,
      representative: bestRows.find((row) => samePair(row, winner))
    };
  }

  return null;
}

function residentialRowScore(row) {
  let score = 0;
  const base = normalize(row.base);
  const subClass = normalize(row.subClass);
  const detail = normalize(row.detail);
  const post = normalize(row.post);
  const accessingAgent = normalize(row.accessingAgent);

  if (base.includes("aplicacao")) score += 8;
  if (!base || base.includes("tarifa de aplicacao")) score += 2;

  if (!post || post === "na" || post.includes("nao se aplica")) score += 5;
  else score -= 6;

  if (!subClass || subClass === "residencial" || subClass.includes("nao se aplica")) score += 4;
  if (subClass.includes("baixa renda")) score -= 20;

  if (!detail || detail === "residencial" || detail.includes("nao se aplica")) score += 4;
  if (detail.includes("baixa renda") || detail.includes("pre pagamento") || detail.includes("prepagamento")) score -= 20;

  if (!accessingAgent || accessingAgent === "na" || accessingAgent.includes("nao se aplica")) score += 2;

  return score;
}

function isResidentialB1Conventional(row) {
  const subgroup = normalize(row.DscSubGrupo);
  const modality = normalize(row.DscModalidadeTarifaria);
  const consumer = normalize([row.DscClasse, row.DscSubClasse, row.DscDetalhe].filter(Boolean).join(" "));
  const post = normalize(row.NomPostoTarifario);

  if (!subgroup.startsWith("b1")) return false;
  if (!modality.includes("convencional")) return false;
  if (!consumer.includes("residencial")) return false;
  if (consumer.includes("baixa renda") || consumer.includes("pre pagamento") || consumer.includes("prepagamento")) return false;
  if (modality.includes("scee") || consumer.includes("scee")) return false;
  return !post || post === "na" || post.includes("nao se aplica");
}

function isCurrent(row, day) {
  const start = normalizeDate(row.DatInicioVigencia);
  const end = normalizeDate(row.DatFimVigencia);
  return (!start || start <= day) && (!end || end >= day);
}

function parseEnergyUnit(unit, tusd, te) {
  const value = normalize(unit).replaceAll(" ", "");
  if (value.includes("mwh")) return { toPerMwh: (number) => Number(number) };
  if (value.includes("kwh")) return { toPerMwh: (number) => Number(number) * 1000 };
  if (!value) {
    const max = Math.max(Number(tusd), Number(te));
    if (max >= 10) return { toPerMwh: (number) => Number(number) };
    if (max > 0 && max < 10) return { toPerMwh: (number) => Number(number) * 1000 };
  }
  return null;
}

function countPairs(rows) {
  const result = [];
  for (const row of rows) {
    let existing = result.find((item) => samePair(row, item.pair));
    if (!existing) {
      existing = { pair: { tusdPerMwh: row.tusdPerMwh, tePerMwh: row.tePerMwh }, count: 0 };
      result.push(existing);
    }
    existing.count += 1;
  }
  return result;
}

function uniquePairs(rows) {
  return countPairs(rows).map((item) => item.pair);
}

function samePair(row, pair) {
  return nearlyEqual(row.tusdPerMwh, pair.tusdPerMwh) && nearlyEqual(row.tePerMwh, pair.tePerMwh);
}

function parsePtNumber(value) {
  const raw = String(value ?? "").trim().replace(/\s/g, "");
  if (!raw) return NaN;
  if (raw.includes(",")) return Number(raw.replace(/\./g, "").replace(",", "."));
  return Number(raw);
}

function normalizeDate(value) {
  const raw = String(value || "").trim();
  if (!raw) return "";
  const iso = raw.match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (iso) return `${iso[1]}-${iso[2]}-${iso[3]}`;
  const br = raw.match(/^(\d{2})\/(\d{2})\/(\d{4})/);
  if (br) return `${br[3]}-${br[2]}-${br[1]}`;
  return "";
}

function parseCsvLine(line, delimiter) {
  const out = [];
  let value = "";
  let quoted = false;
  for (let i = 0; i < line.length; i += 1) {
    const char = line[i];
    if (quoted) {
      if (char === '"' && line[i + 1] === '"') {
        value += '"';
        i += 1;
      } else if (char === '"') quoted = false;
      else value += char;
    } else if (char === '"') quoted = true;
    else if (char === delimiter) {
      out.push(value);
      value = "";
    } else value += char;
  }
  out.push(value);
  return out;
}

function stripBom(value) { return String(value || "").replace(/^\uFEFF/, ""); }
function normalize(value) { return String(value || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-zA-Z0-9]+/g, " ").trim().toLowerCase(); }
function slug(value) { return normalize(value).replace(/\s+/g, "-").slice(0, 80) || "provider"; }
function nearlyEqual(a, b) { return Math.abs(Number(a) - Number(b)) < 0.000001; }
function round6(value) { return Math.round(Number(value) * 1_000_000) / 1_000_000; }
function serialize(value) { return JSON.stringify(value, null, 2); }
