import fs from "node:fs";
import readline from "node:readline";
import { Readable } from "node:stream";

const SOURCE_URL = "https://dadosabertos.aneel.gov.br/dataset/5a583f3e-1646-4f67-bf0f-69db4203e89e/resource/fcf2906c-7c32-4b9b-a637-054e7a5234f4/download/tarifas-homologadas-distribuidoras-energia-eletrica.csv";
const OUTPUT = "beta/national-energy-catalog.js";
const now = new Date();
const today = now.toISOString().slice(0, 10);

const response = await fetch(SOURCE_URL, { headers: { "user-agent": "Volt-Consumo tariff updater" } });
if (!response.ok || !response.body) throw new Error(`ANEEL download failed: ${response.status}`);

const stream = Readable.fromWeb(response.body);
const rl = readline.createInterface({ input: stream, crlfDelay: Infinity });
let headers = null;
const candidates = new Map();

for await (const line of rl) {
  if (!line.trim()) continue;
  const cols = parseCsvLine(line, ";");
  if (!headers) {
    headers = cols.map((value) => stripBom(value));
    continue;
  }
  const row = Object.fromEntries(headers.map((header, index) => [header, cols[index] ?? ""]));
  if (!isResidentialB1Conventional(row)) continue;
  if (!isCurrent(row, today)) continue;
  const tusd = parsePtNumber(row.VlrTUSD);
  const te = parsePtNumber(row.VlrTE);
  if (!Number.isFinite(tusd) || !Number.isFinite(te) || tusd < 0 || te < 0) continue;
  const provider = String(row.SigAgente || "").trim();
  if (!provider) continue;
  const key = normalize(provider);
  const entry = candidates.get(key) || { provider, rows: [] };
  entry.rows.push({
    provider,
    validFrom: normalizeDate(row.DatInicioVigencia),
    validUntil: normalizeDate(row.DatFimVigencia) || null,
    tusd,
    te,
    detail: String(row.DscDetalhe || "").trim(),
    post: String(row.NomPostoTarifario || "").trim(),
    unit: String(row.DscUnidadeTerciaria || "").trim(),
    reh: String(row.DscREH || "").trim()
  });
  candidates.set(key, entry);
}

const rules = [];
for (const [key, entry] of candidates) {
  const normalizedRows = entry.rows.filter((row) => isEnergyUnit(row.unit));
  const pairs = uniquePairs(normalizedRows);
  // Segurança: só automatiza quando a base oficial vigente converge para um
  // único par TUSD+TE. Ambiguidades ficam fora do catálogo automático.
  if (pairs.length !== 1) continue;
  const pair = pairs[0];
  const representative = normalizedRows.find((row) => nearlyEqual(row.tusd, pair.tusd) && nearlyEqual(row.te, pair.te));
  if (!representative) continue;
  rules.push({
    id: `${slug(entry.provider)}-b1-residencial-convencional-${representative.validFrom || today}`,
    utility: "energy",
    provider: entry.provider,
    providerAliases: [entry.provider],
    customerClass: "B1 Residencial — Convencional",
    validFrom: representative.validFrom || today,
    validUntil: representative.validUntil,
    ratePerKwh: round6((pair.tusd + pair.te) / 1000),
    components: { tusdPerMwh: round6(pair.tusd), tePerMwh: round6(pair.te) },
    automatic: true,
    source: representative.reh ? `ANEEL — ${representative.reh}` : "ANEEL — Tarifas de aplicação das distribuidoras",
    sourceUrl: "https://dadosabertos.aneel.gov.br/dataset/tarifas-distribuidoras-energia-eletrica",
    excludes: ["ICMS", "PIS/Cofins", "CIP/COSIP", "bandeira tarifária"]
  });
}

rules.sort((a, b) => a.provider.localeCompare(b.provider, "pt-BR"));
if (!rules.length) throw new Error("No unambiguous current B1 residential conventional tariffs were generated.");

const output = `// AUTO-GENERATED by scripts/update-national-energy-tariffs.mjs\n// Source: ANEEL open tariff dataset. Do not edit manually.\n\nexport const NATIONAL_ENERGY_CATALOG_META = Object.freeze(${serialize({ source: "ANEEL — Tarifas de aplicação das distribuidoras de energia elétrica", sourceUrl: "https://dadosabertos.aneel.gov.br/dataset/tarifas-distribuidoras-energia-eletrica", generatedAt: now.toISOString(), mode: "aneel-weekly", automaticRules: rules.length })});\n\nexport const NATIONAL_ENERGY_CATALOG = Object.freeze(${serialize(rules)}.map((rule) => Object.freeze({ ...rule, providerAliases: Object.freeze(rule.providerAliases || []), components: rule.components ? Object.freeze(rule.components) : null, excludes: Object.freeze(rule.excludes || []) })));\n\nexport function findNationalEnergyRule({ provider = "", date = new Date() } = {}) {\n  const needle = normalize(provider);\n  if (!needle) return null;\n  const when = date instanceof Date ? date : new Date(date);\n  return NATIONAL_ENERGY_CATALOG.find((rule) => rule.automatic && Number.isFinite(rule.ratePerKwh) && matchesProvider(rule, needle) && isCurrent(rule, when)) || null;\n}\n\nexport function listNationalEnergyProviders() { return NATIONAL_ENERGY_CATALOG.filter((rule) => rule.automatic).map((rule) => rule.provider); }\nfunction matchesProvider(rule, needle) { return [rule.provider, ...(rule.providerAliases || [])].some((value) => { const candidate = normalize(value); return candidate === needle || candidate.includes(needle) || needle.includes(candidate); }); }\nfunction isCurrent(rule, date) { if (Number.isNaN(date.getTime())) return false; const day = date.toISOString().slice(0,10); return (!rule.validFrom || day >= rule.validFrom) && (!rule.validUntil || day <= rule.validUntil); }\nfunction normalize(value) { return String(value || "").normalize("NFD").replace(/[\\u0300-\\u036f]/g, "").replace(/[^a-zA-Z0-9]+/g, " ").trim().toLowerCase(); }\n`;

fs.writeFileSync(OUTPUT, output, "utf8");
console.log(`Generated ${rules.length} automatic energy tariff rules in ${OUTPUT}`);

function isResidentialB1Conventional(row) {
  return normalize(row.DscSubGrupo) === "b1"
    && normalize(row.DscModalidadeTarifaria).includes("convencional")
    && normalize(row.DscClasse).includes("residencial");
}
function isCurrent(row, day) {
  const start = normalizeDate(row.DatInicioVigencia);
  const end = normalizeDate(row.DatFimVigencia);
  return (!start || start <= day) && (!end || end >= day);
}
function isEnergyUnit(unit) {
  const value = normalize(unit).replaceAll(" ", "");
  return !value || value.includes("mwh");
}
function uniquePairs(rows) {
  const result = [];
  for (const row of rows) if (!result.some((pair) => nearlyEqual(pair.tusd, row.tusd) && nearlyEqual(pair.te, row.te))) result.push({ tusd: row.tusd, te: row.te });
  return result;
}
function parsePtNumber(value) {
  const raw = String(value ?? "").trim().replace(/\s/g, "");
  if (!raw) return NaN;
  if (raw.includes(",")) return Number(raw.replace(/\./g, "").replace(",", "."));
  return Number(raw);
}
function normalizeDate(value) {
  const raw = String(value || "").trim();
  if (!raw) return "";
  const iso = raw.match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (iso) return `${iso[1]}-${iso[2]}-${iso[3]}`;
  const br = raw.match(/^(\d{2})\/(\d{2})\/(\d{4})/);
  if (br) return `${br[3]}-${br[2]}-${br[1]}`;
  return "";
}
function parseCsvLine(line, delimiter) {
  const out = []; let value = ""; let quoted = false;
  for (let i = 0; i < line.length; i += 1) {
    const char = line[i];
    if (quoted) {
      if (char === '"' && line[i + 1] === '"') { value += '"'; i += 1; }
      else if (char === '"') quoted = false;
      else value += char;
    } else if (char === '"') quoted = true;
    else if (char === delimiter) { out.push(value); value = ""; }
    else value += char;
  }
  out.push(value); return out;
}
function stripBom(value) { return String(value || "").replace(/^\uFEFF/, ""); }
function normalize(value) { return String(value || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-zA-Z0-9]+/g, " ").trim().toLowerCase(); }
function slug(value) { return normalize(value).replace(/\s+/g, "-").slice(0, 80) || "provider"; }
function nearlyEqual(a, b) { return Math.abs(Number(a) - Number(b)) < 0.000001; }
function round6(value) { return Math.round(Number(value) * 1_000_000) / 1_000_000; }
function serialize(value) { return JSON.stringify(value, null, 2); }
