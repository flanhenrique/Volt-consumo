  source_event_id bigint not null unique references public.beta_operational_events(id) on delete cascade,
  rule_key text not null check (rule_key in ('runtime-error', 'operation-failed', 'high-latency')),
  severity text not null check (severity in ('warning', 'critical')),
  component text not null check (char_length(component) between 2 and 60),
  status text not null default 'firing' check (status in ('firing', 'acknowledged')),
