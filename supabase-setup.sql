        and m.status = 'active' and m.role in ('owner', 'admin')
    );
  return jsonb_build_object(
    'can_manage', can_manage,
    'refreshed_at', now(),
    'flags', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'key', f.key,
        'description', f.description,
        'enabled', f.enabled,
        'rollout_percentage', f.rollout_percentage,
