  acknowledged_at timestamptz,
  acknowledged_by uuid references auth.users(id),
  acknowledgement_reason text,
  check ((status = 'firing' and acknowledged_at is null and acknowledged_by is null and acknowledgement_reason is null)
    or (status = 'acknowledged' and acknowledged_at is not null and acknowledged_by is not null and char_length(acknowledgement_reason) between 10 and 500))
);

create or replace function public.beta_raise_operational_alert()
returns trigger language plpgsql security definer set search_path = '' as $$
declare rule text; alert_severity text;
begin
  if new.severity = 'error' and new.event_type = 'runtime.error' then
    rule := 'runtime-error'; alert_severity := 'critical';
  elsif new.severity = 'error' and new.event_type = 'operation.failed' then
    rule := 'operation-failed'; alert_severity := 'critical';
  elsif coalesce(new.duration_ms, 0) >= 2000 then
    rule := 'high-latency'; alert_severity := 'warning';
  else
    return new;
  end if;
  insert into public.beta_operational_alerts (source_event_id, rule_key, severity, component, fired_at)
  values (new.id, rule, alert_severity, new.component, clock_timestamp())
  on conflict (source_event_id) do nothing;
  return new;
end $$;

