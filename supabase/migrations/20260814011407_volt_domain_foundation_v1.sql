create table public.reconciliations (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null,
  bill_id uuid not null,
  calculated_total numeric not null check (calculated_total >= 0),
  invoice_total numeric not null check (invoice_total >= 0),
  difference_amount numeric not null,
  difference_percent numeric,
  measured_minus_billed numeric,
  classification text not null check (classification in ('matching', 'small_difference', 'relevant_difference')),
  status text not null default 'pending' check (status in ('pending', 'reconciled', 'partially_reconciled', 'not_reconciled')),
  engine_version text not null,
  diagnostics jsonb not null default '{}'::jsonb,
  source_type text not null default 'volt_calculated' check (source_type = 'volt_calculated'),
  confidence text not null default 'probable' check (confidence in ('confirmed', 'probable', 'not_identified')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reconciliations_bill_org_fk foreign key (bill_id, organization_id)
    references public.bills(id, organization_id) on delete cascade,
  unique (bill_id),
  unique (id, organization_id)
);

create table public.regulatory_profiles (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null,
  consumer_unit_id uuid not null,
  rule_code text not null,
  regulatory_rule_id uuid references public.regulatory_rules(id) on delete restrict,
  state text not null check (state in ('not_analyzed', 'possible', 'apparent_eligible', 'confirmed_on_bill', 'not_identified')),
  source_type text check (source_type is null or source_type in ('volt_measured', 'user_informed', 'bill_identified', 'volt_calculated', 'rule_predicted')),
  confidence text not null default 'not_identified' check (confidence in ('confirmed', 'probable', 'not_identified')),
  evidence_bill_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint regulatory_profiles_unit_org_fk foreign key (consumer_unit_id, organization_id)
    references public.consumer_units(id, organization_id) on delete cascade,
  constraint regulatory_profiles_bill_org_fk foreign key (evidence_bill_id, organization_id)
    references public.bills(id, organization_id) on delete restrict
);

create table public.rule_applications (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null,
  regulatory_rule_id uuid not null references public.regulatory_rules(id) on delete restrict,
  consumer_unit_id uuid not null,
  billing_cycle_id uuid,
  bill_id uuid,
  bill_component_id uuid,
  engine_stage text not null check (engine_stage in ('legal', 'billing', 'reconciliation')),
  outcome text not null check (outcome in ('applied', 'not_applied', 'possible', 'confirmed', 'not_identified')),
  effect_amount numeric,
  source_type text check (source_type is null or source_type in ('volt_measured', 'user_informed', 'bill_identified', 'volt_calculated', 'rule_predicted')),
  confidence text not null default 'not_identified' check (confidence in ('confirmed', 'probable', 'not_identified')),
  explanation text,
  created_at timestamptz not null default now(),
  constraint rule_applications_unit_org_fk foreign key (consumer_unit_id, organization_id)
    references public.consumer_units(id, organization_id) on delete cascade,
  constraint rule_applications_cycle_org_fk foreign key (billing_cycle_id, organization_id)
    references public.billing_cycles(id, organization_id) on delete cascade,
  constraint rule_applications_bill_org_fk foreign key (bill_id, organization_id)
    references public.bills(id, organization_id) on delete cascade,
  constraint rule_applications_component_org_fk foreign key (bill_component_id, organization_id)
    references public.bill_components(id, organization_id) on delete cascade
);

