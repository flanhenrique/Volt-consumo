create table public.consumer_units (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.beta_organizations(id) on delete cascade,
  created_by uuid not null references auth.users(id) on delete restrict,
  service text not null check (service in ('energy', 'water')),
  measurement_unit text not null check (measurement_unit in ('kWh', 'm3')),
  label text not null,
  country text not null default 'BR' check (country ~ '^[A-Z]{2}$'),
  state text check (state is null or state ~ '^[A-Z]{2}$'),
  city text,
  distributor text,
  class text,
  subclass text,
  system_type text not null default 'not_identified' check (system_type in ('sin', 'isolated', 'not_identified')),
  provider_account_ref text,
  status text not null default 'active' check (status in ('active', 'archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint consumer_units_service_measurement_check check (
    (service = 'energy' and measurement_unit = 'kWh') or
    (service = 'water' and measurement_unit = 'm3')
  ),
  unique (id, organization_id)
);

create table public.billing_cycles (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null,
  consumer_unit_id uuid not null,
  cycle_start date not null,
  cycle_end date not null,
  status text not null default 'open' check (status in ('open', 'closed', 'awaiting_bill', 'billed', 'reconciled')),
  target_consumption numeric check (target_consumption is null or target_consumption >= 0),
  target_cost numeric check (target_cost is null or target_cost >= 0),
  source_type text check (source_type is null or source_type in ('volt_measured', 'user_informed', 'bill_identified', 'volt_calculated', 'rule_predicted')),
  confidence text not null default 'not_identified' check (confidence in ('confirmed', 'probable', 'not_identified')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint billing_cycles_dates_check check (cycle_end >= cycle_start),
  constraint billing_cycles_unit_org_fk foreign key (consumer_unit_id, organization_id)
    references public.consumer_units(id, organization_id) on delete cascade,
  unique (consumer_unit_id, cycle_start, cycle_end),
  unique (id, organization_id)
);

create table public.unit_meter_readings (
  id bigint generated by default as identity primary key,
  organization_id uuid not null,
  consumer_unit_id uuid not null,
  billing_cycle_id uuid,
  value numeric not null check (value >= 0),
  measured_at timestamptz not null,
  source_type text not null check (source_type in ('volt_measured', 'user_informed', 'bill_identified', 'volt_calculated', 'rule_predicted')),
  confidence text not null default 'confirmed' check (confidence in ('confirmed', 'probable', 'not_identified')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint unit_meter_readings_unit_org_fk foreign key (consumer_unit_id, organization_id)
    references public.consumer_units(id, organization_id) on delete cascade,
  constraint unit_meter_readings_cycle_org_fk foreign key (billing_cycle_id, organization_id)
    references public.billing_cycles(id, organization_id) on delete set null,
  unique (consumer_unit_id, value, measured_at)
);

create table public.regulatory_rules (
  id uuid primary key default gen_random_uuid(),
  code text not null,
  name text not null,
  service text not null check (service in ('energy', 'water', 'both')),
  jurisdiction text not null check (jurisdiction in ('federal', 'state', 'municipal', 'distributor')),
  country text not null default 'BR' check (country ~ '^[A-Z]{2}$'),
  state text check (state is null or state ~ '^[A-Z]{2}$'),
  city text,
  distributor text,
  valid_from date not null,
  valid_until date,
  legal_basis text,
  source_title text,
  source_url text,
  conditions jsonb not null default '{}'::jsonb,
  effect jsonb not null default '{}'::jsonb,
  priority integer not null default 100,
  status text not null default 'draft' check (status in ('draft', 'published', 'superseded', 'retired')),
  version integer not null check (version > 0),
  supersedes_rule_id uuid references public.regulatory_rules(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint regulatory_rules_validity_check check (valid_until is null or valid_until >= valid_from),
  unique (code, version)
);

create table public.bills (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null,
  consumer_unit_id uuid not null,
  billing_cycle_id uuid not null,
  revision integer not null default 1 check (revision > 0),
  supersedes_bill_id uuid,
  issued_at date,
  due_date date,
  billing_method text not null default 'not_identified' check (billing_method in ('metered', 'average', 'estimated', 'adjusted', 'not_identified')),
  measured_consumption numeric check (measured_consumption is null or measured_consumption >= 0),
  billed_consumption numeric check (billed_consumption is null or billed_consumption >= 0),
  estimated_total numeric check (estimated_total is null or estimated_total >= 0),
  invoice_total numeric check (invoice_total is null or invoice_total >= 0),
  currency text not null default 'BRL' check (currency ~ '^[A-Z]{3}$'),
  source_type text check (source_type is null or source_type in ('volt_measured', 'user_informed', 'bill_identified', 'volt_calculated', 'rule_predicted')),
  confidence text not null default 'not_identified' check (confidence in ('confirmed', 'probable', 'not_identified')),
  status text not null default 'received' check (status in ('received', 'validated', 'reconciled', 'revised')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint bills_unit_org_fk foreign key (consumer_unit_id, organization_id)
    references public.consumer_units(id, organization_id) on delete cascade,
  constraint bills_cycle_org_fk foreign key (billing_cycle_id, organization_id)
    references public.billing_cycles(id, organization_id) on delete cascade,
  unique (billing_cycle_id, revision),
  unique (id, organization_id),
  constraint bills_supersedes_org_fk foreign key (supersedes_bill_id, organization_id)
    references public.bills(id, organization_id) on delete restrict
);

