create or replace function volt_private.prevent_regulatory_rule_mutation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'regulatory_rules are append-only; create a new version instead';
end;
$$;

revoke all on function volt_private.prevent_regulatory_rule_mutation() from public, anon, authenticated;

drop trigger if exists regulatory_rules_append_only on public.regulatory_rules;
create trigger regulatory_rules_append_only
before update or delete on public.regulatory_rules
for each row execute function volt_private.prevent_regulatory_rule_mutation();

